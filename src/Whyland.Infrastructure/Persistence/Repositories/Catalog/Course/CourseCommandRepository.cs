using Whyland.Domain.Model.Catalog.Course.Repositories;

namespace Whyland.Infrastructure.Persistence.Repositories.Catalog.Course;

/// <summary>
/// The EF Core command repository for the <c>Course</c> aggregate, backed by the shared scoped
/// <see cref="WhylandDbContext"/>; persistence happens through the Unit of Work. It only stages
/// changes, so a course and its link rows commit together.
/// </summary>
/// <param name="context">The scoped EF Core context the repository stages changes on.</param>
public sealed class CourseCommandRepository(WhylandDbContext context) : ICourseCommandRepository
{
    /// <summary>
    /// Reads the tracked course with its category and instructor links. Tracking is required here:
    /// replacing the links is a diff against the loaded collection, not a delete-and-reinsert.
    /// </summary>
    public Task<Domain.Model.Catalog.Course.Entities.Course?> GetByIdAsync(
        long id,
        CancellationToken ct = default)
        => context.Courses
            .Include(x => x.CourseCategories)
            .Include(x => x.CourseInstructors)
            .FirstOrDefaultAsync(x => x.Id == CourseId.From(id), ct);

    /// <summary>
    /// Checks the filtered unique index: only live courses block a slug, so a deleted course frees
    /// its own for a replacement.
    /// </summary>
    public Task<bool> IsSlugTakenAsync(
        string slug,
        long? excludeId = null,
        CancellationToken ct = default)
    {
        var query = context.Courses
            .AsNoTracking()
            .Where(x => x.Slug == slug);

        if (excludeId is { } id)
        {
            var excluded = CourseId.From(id);
            query = query.Where(x => x.Id != excluded);
        }

        return query.AnyAsync(ct);
    }

    /// <summary>Stages a new course; its identity is generated by the provider on save.</summary>
    public async Task AddAsync(
        Domain.Model.Catalog.Course.Entities.Course course,
        CancellationToken ct = default)
        => await context.Courses.AddAsync(course, ct);

    /// <summary>Marks the tracked course and its loaded collection changes for saving.</summary>
    public void Update(Domain.Model.Catalog.Course.Entities.Course course)
        => context.Courses.Update(course);

    /// <summary>Stages the soft-delete flag; the row and its links stay in the database.</summary>
    public void SoftDelete(Domain.Model.Catalog.Course.Entities.Course course)
    {
        course.MarkDeleted();
        context.Courses.Update(course);
    }
}
